

<?php
//Aquí se utiliza echo
/*
* El echo muestra el texto que se le indica   
* Permite mostrar varios argumentos que estén separados por comas.
* Además no devuelve ningún valor al contrario que el print
*/
echo ("Hola Mundo");

echo "<br>";

//Ahora se utilizará con el método print

/*

*Cuando se utiliza el print para mostrar texto por pantalla

*Solo acepta un parámetro por vez y devuelve el valor 1 siempre

*/

print "Hola Mundo";

?>